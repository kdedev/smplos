#!/bin/bash
# smplOS Dev Tool: Generate all config files for every theme
# Reads colors.toml from each theme, expands _templates, writes results into the theme dir
# Run this whenever you change a template or add a new theme.
#
# Variable naming: colors.toml defines WHAT each color DOES (semantic roles),
# not what it looks like. The terminal palette (ANSI slots 0-15) is auto-derived.
# Override with explicit term_N if a slot needs to differ from its semantic source.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
THEMES_DIR="$SCRIPT_DIR/shared/themes"
TEMPLATES_DIR="$THEMES_DIR/_templates"

if [[ ! -d "$TEMPLATES_DIR" ]]; then
  echo "ERROR: Templates directory not found: $TEMPLATES_DIR"
  exit 1
fi

# nemo.css is intentionally NOT generated from a .tpl — it has its own
# generator (regen-nemo-css.py) with correct GTK CSS specificity and submenu
# reset blocks that the simple sed-based .tpl expansion cannot reproduce.
# If nemo.css.tpl is ever (re)created, this script would silently overwrite
# all 15 nemo.css files with broken CSS, reintroducing black-on-black menus.
# Use regen-all-themes.sh as the single entry point for all theme generation.
if [[ -f "$TEMPLATES_DIR/nemo.css.tpl" ]]; then
  echo "ERROR: nemo.css.tpl must not exist — nemo.css is generated by regen-nemo-css.py"
  echo "       Delete _templates/nemo.css.tpl and run regen-all-themes.sh instead."
  exit 1
fi

hex_to_rgb() {
  local hex="${1#\#}"
  printf "%d,%d,%d" "0x${hex:0:2}" "0x${hex:2:2}" "0x${hex:4:2}"
}

# Add a key+value to the sed script with plain, _strip, and _rgb variants
emit_sed_entry() {
  local key="$1" value="$2" out="$3"
  [[ -n "$value" ]] || return 0
  printf 's|{{ %s }}|%s|g\n' "$key" "$value" >> "$out"
  printf 's|{{ %s_strip }}|%s|g\n' "$key" "${value#\#}" >> "$out"
  if [[ $value =~ ^# ]]; then
    local rgb
    rgb=$(hex_to_rgb "$value")
    printf 's|{{ %s_rgb }}|%s|g\n' "$key" "$rgb" >> "$out"
  fi
}

generate_theme() {
  local theme_dir="$1"
  local name="$(basename "$theme_dir")"
  local colors_file="$theme_dir/colors.toml"

  if [[ ! -f "$colors_file" ]]; then
    echo "  SKIP $name (no colors.toml)"
    return
  fi

  # Parse colors.toml into associative array
  declare -A pairs=()
  while IFS='=' read -r key value; do
    key="${key//[\"\' ]/}"
    [[ $key && $key != \#* ]] || continue
    value="${value#*[\"\']}"
    value="${value%%[\"\']*}"
    pairs["$key"]="$value"
  done < "$colors_file"

  pairs[app_background_opacity]=$(python3 "$SCRIPT_DIR/theme_opacity.py" "$colors_file")
  pairs[glass]="${pairs[glass]-false}"
  if [[ "${pairs[glass]}" != true && "${pairs[glass]}" != false ]]; then
    echo "ERROR: $name: glass must be true or false" >&2
    return 1
  fi
  pairs[glass_background]="${pairs[glass_background]:-${pairs[background]}}"
  pairs[glass_foreground]="${pairs[glass_foreground]:-${pairs[foreground]}}"
  pairs[glass_fg_dim]="${pairs[glass_fg_dim]:-${pairs[fg_dim]}}"
  pairs[glass_accent]="${pairs[glass_accent]:-${pairs[accent]}}"
  pairs[glass_outline]="${pairs[glass_outline]:-${pairs[background]}}"

  # Optional Hyprland window effects (shadow tint, inner glow, animated gradient
  # angle). Every default reproduces the classic look, so a theme that sets none
  # of these renders exactly as before. Flags become 0/1 for hyprlang and Lua.
  for flag in glow border_animation hud_frame hud_sweep hud_hide_border; do
    pairs[$flag]="${pairs[$flag]-false}"
    if [[ "${pairs[$flag]}" != true && "${pairs[$flag]}" != false ]]; then
      echo "ERROR: $name: $flag must be true or false" >&2
      return 1
    fi
    pairs[${flag}_flag]=$([[ "${pairs[$flag]}" == true ]] && echo 1 || echo 0)
  done
  # hud_hide_border drops Hyprland's own border so the HUD frame is the only
  # line: Hyprland is given border size 0 (its window box grows by that width)
  # while border_size stays the configured width for compositors without the
  # frame. Without the frame there would be no line at all.
  if [[ "${pairs[hud_hide_border]}" == true && "${pairs[hud_frame]}" != true ]]; then
    echo "ERROR: $name: hud_hide_border needs hud_frame = true" >&2
    return 1
  fi
  pairs[border_size]="${pairs[border_size]:-2}"
  pairs[hypr_border_size]=$([[ "${pairs[hud_hide_border]}" == true ]] && echo 0 || echo "${pairs[border_size]}")
  # Window corner shape. rounding_power 2 is a circle (Hyprland's default);
  # 1 turns "rounding" into straight 45 degree cuts with legs of rounding / 2 - 1.
  pairs[rounding_power]="${pairs[rounding_power]-2.0}"
  if [[ ! "${pairs[rounding_power]}" =~ ^(10(\.0+)?|[1-9](\.[0-9]+)?)$ ]]; then
    echo "ERROR: $name: rounding_power must be a number from 1 to 10" >&2
    return 1
  fi
  # Corners drawn by rofi, the Nemo quick preview and niri are circular only, so
  # a theme with 45 degree cuts sets this to 0 and leaves the shape to Hyprland.
  pairs[app_rounding]="${pairs[app_rounding]-${pairs[rounding]:-10}}"
  if [[ ! "${pairs[app_rounding]}" =~ ^[0-9]+$ ]]; then
    echo "ERROR: $name: app_rounding must be a non-negative integer" >&2
    return 1
  fi
  # HUD frames (smpl-hud Hyprland plugin): pixel distances and the style name,
  # validated here so the plugin can trust the generated variables.
  for hud_pair in hud_gap:5 hud_chamfer:10 hud_float_glow_range:0; do
    pairs[${hud_pair%%:*}]="${pairs[${hud_pair%%:*}]-${hud_pair#*:}}"
    if [[ ! "${pairs[${hud_pair%%:*}]}" =~ ^[0-9]+$ ]]; then
      echo "ERROR: $name: ${hud_pair%%:*} must be a non-negative integer" >&2
      return 1
    fi
  done
  pairs[hud_line_width]="${pairs[hud_line_width]-3}"
  if [[ ! "${pairs[hud_line_width]}" =~ ^[1-9](\.[0-9]+)?$ ]]; then
    echo "ERROR: $name: hud_line_width must be a number from 1 to 9.99" >&2
    return 1
  fi
  pairs[hud_style]="${pairs[hud_style]-scifi}"
  if [[ ! "${pairs[hud_style]}" =~ ^[a-z0-9_-]+$ ]]; then
    echo "ERROR: $name: hud_style must be a style name (lowercase letters, digits, - and _)" >&2
    return 1
  fi
  # The travelling glow (hud_sweep): speed in px per second and length in px,
  # as integers inside the range the plugin accepts. Plain numbers, so a value
  # like 010 is never read as octal.
  for hud_range in hud_sweep_speed:80:10:400 hud_sweep_length:180:40:600; do
    IFS=: read -r hud_key hud_default hud_min hud_max <<< "$hud_range"
    pairs[$hud_key]="${pairs[$hud_key]-$hud_default}"
    if [[ ! "${pairs[$hud_key]}" =~ ^[0-9]{1,4}$ ]] \
      || (( 10#${pairs[$hud_key]} < hud_min || 10#${pairs[$hud_key]} > hud_max )); then
      echo "ERROR: $name: $hud_key must be an integer from $hud_min to $hud_max" >&2
      return 1
    fi
    pairs[$hud_key]=$((10#${pairs[$hud_key]}))
  done
  # The colour of the characters of a glyph style such as "matrix", as
  # rgb(rrggbb), or none to give them the colours of the line. Always written
  # out: the sed expansion skips an empty value and would leave the placeholder.
  pairs[hud_glyph_color]="${pairs[hud_glyph_color]-none}"
  if [[ ! "${pairs[hud_glyph_color]}" =~ ^(none|rgb\([0-9a-fA-F]{6}\))$ ]]; then
    echo "ERROR: $name: hud_glyph_color must be none or rgb(rrggbb)" >&2
    return 1
  fi
  local accent_hex="${pairs[accent]:-}"
  pairs[shadow_range]="${pairs[shadow_range]:-2}"
  pairs[shadow_render_power]="${pairs[shadow_render_power]:-3}"
  pairs[shadow_color]="${pairs[shadow_color]:-rgba(1a1a1aee)}"
  pairs[shadow_color_inactive]="${pairs[shadow_color_inactive]:-${pairs[shadow_color]}}"
  pairs[glow_range]="${pairs[glow_range]:-10}"
  pairs[glow_render_power]="${pairs[glow_render_power]:-3}"
  pairs[glow_color]="${pairs[glow_color]:-rgba(${accent_hex#\#}b0)}"
  pairs[glow_color_inactive]="${pairs[glow_color_inactive]:-${pairs[glow_color]}}"

  # --- Derive terminal palette (ANSI 0-15) from semantic names ---
  # Each slot maps to a semantic variable. Themes can override with term_N.
  local -a term_sources=(
    surface danger success warning accent accent_alt
    info fg_alt muted danger_bright success_bright warning_bright
    accent_bright accent_alt_bright info_bright fg_dim
  )

  for slot in {0..15}; do
    local tkey="term_${slot}"
    if [[ -z "${pairs[$tkey]:-}" ]]; then
      pairs["$tkey"]="${pairs[${term_sources[$slot]}]:-}"
    fi
  done

  # Build sed script from all pairs
  local sed_script
  sed_script=$(mktemp)

  for key in "${!pairs[@]}"; do
    emit_sed_entry "$key" "${pairs[$key]}" "$sed_script"
  done

  # Decoration defaults (applied only if theme didn't set them)
  for pair in "rounding:10" "gaps_in:2" "gaps_out:4" "blur_size:6" "blur_passes:3" "opacity_active:1.0" "opacity_inactive:1.0" "popup_opacity:0.60" "messenger_opacity:0.85" "browser_opacity:1.0"; do
    local dkey="${pair%%:*}" dval="${pair#*:}"
    if ! grep -q "{{ ${dkey} }}" "$sed_script"; then
      printf 's|{{ %s }}|%s|g\n' "$dkey" "$dval" >> "$sed_script"
    fi
  done

  # Border color defaults: derive from accent/muted if not explicitly set
  if [[ -z "${pairs[border_active]:-}" ]]; then
    local a_hex="${pairs[accent]:-}"
    a_hex="${a_hex#\#}"
    printf 's|{{ border_active }}|rgb(%s)|g\n' "$a_hex" >> "$sed_script"
  fi
  if [[ -z "${pairs[border_inactive]:-}" ]]; then
    local m_hex="${pairs[muted]:-}"
    m_hex="${m_hex#\#}"
    printf 's|{{ border_inactive }}|rgba(%saa)|g\n' "$m_hex" >> "$sed_script"
  fi

  # Autosuggestion default: derive from muted if not explicitly set
  if [[ -z "${pairs[autosuggestion]:-}" ]]; then
    local as_val="${pairs[muted]:-}"
    if [[ -n "$as_val" ]]; then
      emit_sed_entry "autosuggestion" "$as_val" "$sed_script"
    fi
  fi

  # Expand each template into the theme directory
  local count=0
  for tpl in "$TEMPLATES_DIR"/*.tpl; do
    local filename
    filename=$(basename "$tpl" .tpl)
    sed -f "$sed_script" "$tpl" > "$theme_dir/$filename"
    count=$((count + 1))
  done

  rm "$sed_script"
  echo "  OK   $name ($count files generated)"
}

echo "Generating theme configs from templates..."
echo ""

for theme_dir in "$THEMES_DIR"/*/; do
  [[ "$(basename "$theme_dir")" == _* ]] && continue
  generate_theme "$theme_dir"
done

echo ""
echo "Done. All themes now have pre-baked config files."
